//! Material domain layout inside a Quillshade project (spec §5, design §4): sources under `quillshade/material/`,
//! generated WESL / internal textures / baked gradients under `assets/quillshade/material/`, the generated Rust
//! module in `crates/quillshade/src/material/`.

use std::path::PathBuf;

use project_core::DomainId;

pub use project_core::layout::{OpenError, Project, ProjectSettings};

/// Id of the Material domain; also its module in the umbrella crate (`crate::material`).
pub const MATERIAL: DomainId = DomainId::new(shader_codegen_rust::MODULE);
/// Material sources relative to the project root.
pub const MATERIAL_DIR: &str = "quillshade/material";
/// Directory with data-driven user nodes inside [`MATERIAL_DIR`].
pub const USER_NODES_DIR: &str = ".nodes";
/// WESL autogen location relative to the project root.
pub const AUTOGEN_DIR: &str = "assets/quillshade/material/autogen";
/// Internal textures (design §2) relative to the project root; owned by the editor through [`INTERNAL_MARKER`].
pub const INTERNAL_DIR: &str = "assets/quillshade/material/internal";
/// Baked gradient collection PNGs (gradient design §5) relative to the project root; owned by the editor through
/// [`INTERNAL_MARKER`], like [`INTERNAL_DIR`].
pub const GRADIENTS_DIR: &str = "assets/quillshade/material/gradients";
/// Marker file inside [`INTERNAL_DIR`] and [`GRADIENTS_DIR`]: binary files cannot carry the AUTOGENERATED line, so
/// the directory does.
pub const INTERNAL_MARKER: &str = project_core::files::OWNED_DIR_MARKER;

/// Material paths of a [`Project`].
pub trait MaterialLayout {
    /// Source root of the Material domain (`quillshade/material`).
    fn material_dir(&self) -> PathBuf;
    /// Generated WESL and the baked manifest (`assets/quillshade/material/autogen`).
    fn autogen_dir(&self) -> PathBuf;
    /// Internal textures (`assets/quillshade/material/internal`).
    fn internal_dir(&self) -> PathBuf;
    /// Baked gradient collections (`assets/quillshade/material/gradients`).
    fn gradients_dir(&self) -> PathBuf;
    /// Generated Rust module (`crates/quillshade/src/material`).
    fn material_module_dir(&self) -> PathBuf;
    /// Source file of an asset (`quillshade/material/{path}.{suffix}.ron`).
    fn asset_file(&self, path: &str, suffix: &str) -> PathBuf;
    /// Creates `quillshade/` (with a default `project.ron`) and `quillshade/material/` if missing.
    fn ensure_material_dir(&self) -> std::io::Result<()>;
}

impl MaterialLayout for Project {
    fn material_dir(&self) -> PathBuf {
        self.domain_dir(MATERIAL)
    }

    fn autogen_dir(&self) -> PathBuf {
        self.root.join(AUTOGEN_DIR)
    }

    fn internal_dir(&self) -> PathBuf {
        self.root.join(INTERNAL_DIR)
    }

    fn gradients_dir(&self) -> PathBuf {
        self.root.join(GRADIENTS_DIR)
    }

    fn material_module_dir(&self) -> PathBuf {
        self.module_dir(MATERIAL)
    }

    fn asset_file(&self, path: &str, suffix: &str) -> PathBuf {
        self.material_dir().join(format!("{path}.{suffix}.ron"))
    }

    fn ensure_material_dir(&self) -> std::io::Result<()> {
        self.ensure_layout()?;
        std::fs::create_dir_all(self.material_dir())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn material_paths_follow_the_quillshade_layout() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("Cargo.toml"), "[package]\nname = \"game\"\n").unwrap();
        std::fs::create_dir(dir.path().join("assets")).unwrap();
        let p = Project::open(dir.path()).unwrap();
        assert_eq!(p.rel(&p.material_dir()), MATERIAL_DIR);
        assert_eq!(p.output_dir(MATERIAL).join("autogen"), p.autogen_dir());
        assert_eq!(p.output_dir(MATERIAL).join("internal"), p.internal_dir());
        assert_eq!(p.output_dir(MATERIAL).join("gradients"), p.gradients_dir());
        assert_eq!(p.rel(&p.material_module_dir()), "crates/quillshade/src/material");
        assert_eq!(p.rel(&p.asset_file("env/rock", "material")), "quillshade/material/env/rock.material.ron");
        assert!(!p.material_dir().exists());
        p.ensure_material_dir().unwrap();
        assert!(p.material_dir().is_dir() && p.settings_path().is_file());
    }
}
