//! Project detection and directory layout (spec §5).

use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use shader_codegen_rust::BevyDep;
use shader_graph_core::{Code, Diagnostic};

/// Settings file inside `shaders/`.
pub const SETTINGS_FILE: &str = ".shader-editor.ron";
/// Directory with data-driven user nodes inside `shaders/`.
pub const USER_NODES_DIR: &str = ".nodes";
/// Generated crate location relative to the project root.
pub const CRATE_DIR: &str = "crates/shaders";
/// WESL autogen location relative to the project root.
pub const AUTOGEN_DIR: &str = "assets/shaders/autogen";
/// Internal textures (design §2) relative to the project root; owned by the editor through [`INTERNAL_MARKER`].
pub const INTERNAL_DIR: &str = "assets/shaders/internal";
/// Marker file inside [`INTERNAL_DIR`]: binary files cannot carry the AUTOGENERATED line, so the directory does.
pub const INTERNAL_MARKER: &str = ".autogen";

#[derive(Debug, thiserror::Error)]
pub enum OpenError {
    #[error("`{0}` is not a directory")]
    NotADirectory(PathBuf),
    #[error("`{0}` is not a project: Cargo.toml is missing")]
    NoCargoToml(PathBuf),
    #[error("`{0}` is not a project: assets/ directory is missing")]
    NoAssets(PathBuf),
    #[error("cannot set up `{0}`: {1}")]
    Io(PathBuf, std::io::Error),
}

/// Project-level options stored in `shaders/.shader-editor.ron`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ProjectSettings {
    pub format_version: u32,
    /// Add the generation date to autogen headers (breaks byte-for-byte determinism across days).
    #[serde(default)]
    pub header_date: bool,
}

impl Default for ProjectSettings {
    fn default() -> Self {
        ProjectSettings { format_version: 1, header_date: false }
    }
}

/// Opened game project.
#[derive(Debug, Clone)]
pub struct Project {
    pub root: PathBuf,
    pub settings: ProjectSettings,
}

impl Project {
    /// Opens `root`, which must contain `Cargo.toml` and `assets/`.
    pub fn open(root: impl AsRef<Path>) -> Result<Project, OpenError> {
        let root = root.as_ref();
        let root = root.canonicalize().map_or_else(|_| root.to_path_buf(), without_verbatim_prefix);
        if !root.is_dir() {
            return Err(OpenError::NotADirectory(root));
        }
        if !root.join("Cargo.toml").is_file() {
            return Err(OpenError::NoCargoToml(root));
        }
        if !root.join("assets").is_dir() {
            return Err(OpenError::NoAssets(root));
        }
        let settings = std::fs::read_to_string(root.join("shaders").join(SETTINGS_FILE))
            .ok()
            .and_then(|t| ron::from_str(&t).ok())
            .unwrap_or_default();
        Ok(Project { root, settings })
    }

    /// Sets up a game crate as a project ("New project" in the editor): `root` must contain `Cargo.toml`;
    /// `assets/` and `shaders/` (with default settings) are created if missing.
    pub fn create(root: impl AsRef<Path>) -> Result<Project, OpenError> {
        let root = root.as_ref();
        let io = |e| OpenError::Io(root.to_path_buf(), e);
        if root.join("Cargo.toml").is_file() {
            std::fs::create_dir_all(root.join("assets")).map_err(io)?;
        }
        let project = Project::open(root)?;
        project.ensure_shaders_dir().map_err(io)?;
        Ok(project)
    }

    pub fn shaders_dir(&self) -> PathBuf {
        self.root.join("shaders")
    }

    /// The game's `assets/` directory (Texture asset paths are relative to it).
    pub fn assets_dir(&self) -> PathBuf {
        self.root.join("assets")
    }

    pub fn autogen_dir(&self) -> PathBuf {
        self.root.join(AUTOGEN_DIR)
    }

    pub fn internal_dir(&self) -> PathBuf {
        self.root.join(INTERNAL_DIR)
    }

    pub fn crate_dir(&self) -> PathBuf {
        self.root.join(CRATE_DIR)
    }

    pub fn settings_path(&self) -> PathBuf {
        self.shaders_dir().join(SETTINGS_FILE)
    }

    /// Source file of an asset (`shaders/{path}.{suffix}.ron`).
    pub fn asset_file(&self, path: &str, suffix: &str) -> PathBuf {
        self.shaders_dir().join(format!("{path}.{suffix}.ron"))
    }

    /// Project-relative display path.
    pub fn rel(&self, p: &Path) -> String {
        p.strip_prefix(&self.root).unwrap_or(p).to_string_lossy().replace('\\', "/")
    }

    /// Creates `shaders/` (with default settings) if missing.
    pub fn ensure_shaders_dir(&self) -> std::io::Result<()> {
        std::fs::create_dir_all(self.shaders_dir())?;
        if !self.settings_path().exists() {
            let text = ron::ser::to_string_pretty(&self.settings, ron::ser::PrettyConfig::new().struct_names(true))
                .expect("settings serialization");
            std::fs::write(self.settings_path(), text + "\n")?;
        }
        Ok(())
    }

    /// How the generated crate depends on Bevy (decision 0019): through the workspace when the root `Cargo.toml`
    /// declares `[workspace.dependencies] bevy`, or itself takes `bevy = { workspace = true }` (the game is a member
    /// of an outer workspace).
    pub fn bevy_dep(&self) -> BevyDep {
        let Some(doc) =
            std::fs::read_to_string(self.root.join("Cargo.toml")).ok().and_then(|t| t.parse::<toml::Table>().ok())
        else {
            return BevyDep::Version;
        };
        let declared = doc.get("workspace").and_then(|w| w.get("dependencies")).and_then(|d| d.get("bevy")).is_some();
        let inherited = doc
            .get("dependencies")
            .and_then(|d| d.get("bevy"))
            .and_then(|b| b.get("workspace"))
            .and_then(|w| w.as_bool())
            .unwrap_or(false);
        if declared || inherited { BevyDep::Workspace } else { BevyDep::Version }
    }

    /// W105: `crates/shaders` missing from `[workspace.members]` of the root `Cargo.toml`.
    pub fn workspace_warning(&self) -> Option<Diagnostic> {
        let text = std::fs::read_to_string(self.root.join("Cargo.toml")).ok()?;
        let doc: toml::Table = text.parse().ok()?;
        let members: Vec<String> = doc
            .get("workspace")
            .and_then(|w| w.get("members"))
            .and_then(|m| m.as_array())
            .map(|a| a.iter().filter_map(|v| v.as_str().map(str::to_string)).collect())
            .unwrap_or_default();
        if members.iter().any(|m| glob_match(m.trim_end_matches('/'), CRATE_DIR)) {
            return None;
        }
        let hint = if doc.contains_key("workspace") {
            format!("add \"{CRATE_DIR}\" to [workspace] members, e.g. members = [\"{CRATE_DIR}\"]")
        } else {
            format!(
                "add to the root Cargo.toml:\n[workspace]\nmembers = [\"{CRATE_DIR}\"]\n\nand to [dependencies]: shaders = {{ path = \"{CRATE_DIR}\" }}"
            )
        };
        Some(
            Diagnostic::new(Code::W105, format!("{CRATE_DIR} is not in [workspace.members]; {hint}"))
                .in_asset("Cargo.toml"),
        )
    }
}

/// Minimal cargo-style glob: `*` matches one path segment.
fn glob_match(pattern: &str, path: &str) -> bool {
    let p: Vec<&str> = pattern.split('/').collect();
    let s: Vec<&str> = path.split('/').collect();
    p.len() == s.len()
        && p.iter().zip(&s).all(|(a, b)| {
            if let Some((pre, post)) = a.split_once('*') { b.starts_with(pre) && b.ends_with(post) } else { a == b }
        })
}

/// Drops the `\\?\` prefix Windows `canonicalize` adds (`\\?\C:\…`, `\\?\UNC\server\…`): a verbatim path takes `/`
/// literally, while layout constants and asset paths joined onto the root use `/` separators. Unlike `dunce`, it strips
/// the prefix even where the plain form means another path (reserved device names, components ending in `.` or a
/// space): acceptable for a project directory.
fn without_verbatim_prefix(p: PathBuf) -> PathBuf {
    let Some(s) = p.to_str() else { return p };
    if let Some(rest) = s.strip_prefix(r"\\?\UNC\") {
        return PathBuf::from(format!(r"\\{rest}"));
    }
    match s.strip_prefix(r"\\?\") {
        Some(rest) if rest.as_bytes().get(1) == Some(&b':') && rest.as_bytes()[0].is_ascii_alphabetic() => {
            PathBuf::from(rest)
        }
        _ => p,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn globs() {
        assert!(glob_match("crates/*", "crates/shaders"));
        assert!(glob_match("crates/shaders", "crates/shaders"));
        assert!(!glob_match("crates/*", "crates/shaders/x"));
        assert!(!glob_match("other/*", "crates/shaders"));
    }

    #[test]
    fn bevy_dep_follows_the_root_manifest() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::create_dir(dir.path().join("assets")).unwrap();
        let dep = |manifest: &str| {
            std::fs::write(dir.path().join("Cargo.toml"), manifest).unwrap();
            Project::open(dir.path()).unwrap().bevy_dep()
        };
        assert_eq!(dep("[package]\nname = \"game\"\n[dependencies]\nbevy = \"0.20\"\n"), BevyDep::Version);
        assert_eq!(dep("[workspace]\n[workspace.dependencies]\nbevy = { version = \"0.20\" }\n"), BevyDep::Workspace);
        assert_eq!(
            dep("[package]\nname = \"game\"\n[dependencies]\nbevy = { workspace = true }\n"),
            BevyDep::Workspace
        );
        assert_eq!(dep("not toml ["), BevyDep::Version);
    }

    #[test]
    fn verbatim_prefix_is_dropped() {
        let strip = |p: &str| without_verbatim_prefix(PathBuf::from(p));
        assert_eq!(strip(r"\\?\C:\games\rock"), PathBuf::from(r"C:\games\rock"));
        assert_eq!(strip(r"\\?\UNC\server\share\rock"), PathBuf::from(r"\\server\share\rock"));
        // No drive letter to fall back to: kept as is.
        assert_eq!(strip(r"\\?\Volume{0a1b}\rock"), PathBuf::from(r"\\?\Volume{0a1b}\rock"));
        assert_eq!(strip("/home/u/rock"), PathBuf::from("/home/u/rock"));
    }

    #[test]
    fn create_sets_up_a_crate() {
        let dir = tempfile::tempdir().unwrap();
        assert!(matches!(Project::create(dir.path()), Err(OpenError::NoCargoToml(_))));
        assert!(!dir.path().join("assets").exists());
        std::fs::write(dir.path().join("Cargo.toml"), "[package]\nname = \"game\"\n").unwrap();
        let project = Project::create(dir.path()).unwrap();
        assert!(project.root.join("assets").is_dir());
        assert!(project.settings_path().is_file());
        Project::create(dir.path()).unwrap();
    }
}
