#[test]
fn regen_fixtures_and_is_idempotent() {
    let (_d, p) = temp_project();
    let bevy = BevySources::discover();
    let opts = RegenOptions { compile_check: bevy.as_ref(), ..Default::default() };
    let report = regenerate(&p, &opts).unwrap();
    for d in report.diagnostics() {
        eprintln!("{d}");
    }
    assert!(!report.has_errors());
    let wesl = read(&p.root.join("assets/quillshade/material/autogen/dir_env/mat_rock_wet.wesl"));
    assert!(
        wesl.starts_with("// AUTOGENERATED by shader-editor v1 from quillshade/material/env/rock_wet.material.ron")
    );
    assert!(wesl.contains("import super::super::functions::dir_common::fun_wet_mask::{WetMaskOut, fun_wet_mask};"));
    let rs = read(&p.root.join("crates/quillshade/src/material/materials/dir_env/mat_rock_wet.rs"));
    assert!(
        rs.contains("pub(crate) fn new(inp_albedo: Handle<Image>, inp_normal_map: Handle<Image>, inp_speed: f32, inp_tint: LinearRgba, inp_wetness: f32) -> Self"),
        "{rs}"
    );
    assert!(p.root.join("assets/quillshade/material/autogen/stdlib/math.wesl").exists());
    assert!(p.root.join("assets/quillshade/material/autogen/functions/dir_common/fun_wet_mask.wesl").exists());

    // Second run: nothing changes, mtimes untouched.
    let mtime = |f: &str| std::fs::metadata(p.root.join(f)).unwrap().modified().unwrap();
    let before = mtime("assets/quillshade/material/autogen/dir_env/mat_rock_wet.wesl");
    std::thread::sleep(std::time::Duration::from_millis(20));
    let again = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(again.changes.is_empty(), "{:?}", again.changes);
    assert_eq!(before, mtime("assets/quillshade/material/autogen/dir_env/mat_rock_wet.wesl"));
}

