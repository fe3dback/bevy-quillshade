//! End-to-end pipeline tests on a temporary project.

use std::path::Path;

use shader_codegen_wesl::check::BevySources;
use shader_graph_core::Code;
use shader_project::assets::{AssetId, AssetType};
use shader_project::{Project, RegenOptions, fixtures, ops, regenerate};

fn temp_project() -> (tempfile::TempDir, Project) {
    let dir = tempfile::tempdir().unwrap();
    std::fs::write(dir.path().join("Cargo.toml"), "[workspace]\nmembers = [\"crates/*\"]\n").unwrap();
    std::fs::create_dir_all(dir.path().join("assets")).unwrap();
    let p = Project::open(dir.path()).unwrap();
    for (path, is_fn, asset) in fixtures::all() {
        let id = AssetId::new(if is_fn { AssetType::Function } else { AssetType::Material }, path);
        ops::save(&p, &id, &asset).unwrap();
    }
    (dir, p)
}

fn read(p: &Path) -> String {
    std::fs::read_to_string(p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
}

#[test]
fn open_rejects_non_projects() {
    let dir = tempfile::tempdir().unwrap();
    assert!(Project::open(dir.path()).is_err());
    std::fs::write(dir.path().join("Cargo.toml"), "").unwrap();
    let e = Project::open(dir.path()).unwrap_err().to_string();
    assert!(e.contains("assets"), "{e}");
}

#[test]
fn regen_fixtures_and_is_idempotent() {
    let (_d, p) = temp_project();
    let bevy = BevySources::discover();
    let opts = RegenOptions { compile_check: bevy.as_ref(), ..Default::default() };
    let report = regenerate(&p, &opts).unwrap();
    for d in report.diagnostics() {
        eprintln!("{d}");
    }
    assert!(!report.has_errors());
    let wesl = read(&p.root.join("assets/shaders/autogen/env/rock_wet.wesl"));
    assert!(wesl.starts_with("// AUTOGENERATED by shader-editor v1 from shaders/env/rock_wet.material.ron"));
    assert!(wesl.contains("import super::super::functions::common::wet_mask::{WetMaskOut, wet_mask};"));
    let rs = read(&p.root.join("crates/shaders/src/materials/env/rock_wet.rs"));
    assert!(
        rs.contains("pub fn new(albedo: Handle<Image>, normal_map: Handle<Image>, tint: LinearRgba, wetness: f32, speed: f32) -> Self"),
        "{rs}"
    );
    assert!(p.root.join("assets/shaders/autogen/stdlib/math.wesl").exists());
    assert!(p.root.join("assets/shaders/autogen/functions/common/wet_mask.wesl").exists());

    // Second run: nothing changes, mtimes untouched.
    let mtime = |f: &str| std::fs::metadata(p.root.join(f)).unwrap().modified().unwrap();
    let before = mtime("assets/shaders/autogen/env/rock_wet.wesl");
    std::thread::sleep(std::time::Duration::from_millis(20));
    let again = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(again.changes.is_empty(), "{:?}", again.changes);
    assert_eq!(before, mtime("assets/shaders/autogen/env/rock_wet.wesl"));
}

#[test]
fn orphans_removed_and_foreign_files_kept() {
    let (_d, p) = temp_project();
    regenerate(&p, &RegenOptions::default()).unwrap();
    let foreign = p.root.join("assets/shaders/autogen/env/handwritten.wesl");
    std::fs::write(&foreign, "fn x() {}\n").unwrap();
    ops::delete(&p, &AssetId::new(AssetType::Material, "env/flag")).unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(!r.has_errors());
    assert!(!p.root.join("assets/shaders/autogen/env/flag.wesl").exists());
    assert!(!p.root.join("crates/shaders/src/materials/env/flag.rs").exists());
    assert!(foreign.exists());
    // Rename updates autogen.
    let id = ops::rename(&p, &AssetId::new(AssetType::Material, "env/water"), "lake/water").unwrap();
    assert_eq!(id.path, "lake/water");
    regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(p.root.join("assets/shaders/autogen/lake/water.wesl").exists());
    assert!(!p.root.join("assets/shaders/autogen/env/water.wesl").exists());
    assert!(read(&p.root.join("crates/shaders/src/materials/mod.rs")).contains("pub mod lake;"));
}

#[test]
fn foreign_file_blocks_write_with_e008() {
    let (_d, p) = temp_project();
    let target = p.root.join("assets/shaders/autogen/env/rock_wet.wesl");
    std::fs::create_dir_all(target.parent().unwrap()).unwrap();
    std::fs::write(&target, "// my own shader\n").unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(r.diagnostics().any(|d| d.code == Code::E008));
    assert_eq!(read(&target), "// my own shader\n");
}

#[test]
fn function_rename_updates_callers() {
    let (_d, p) = temp_project();
    ops::rename(&p, &AssetId::new(AssetType::Function, "common/wet_mask"), "lib/wet_mask").unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(!r.has_errors(), "{:?}", r.diagnostics().collect::<Vec<_>>());
    assert!(read(&p.root.join("assets/shaders/autogen/env/rock_wet.wesl")).contains("functions::lib::wet_mask"));
}

#[test]
fn errors_block_only_affected_asset() {
    let (_d, p) = temp_project();
    regenerate(&p, &RegenOptions::default()).unwrap();
    let old = read(&p.root.join("assets/shaders/autogen/env/water.wesl"));
    // Break water: remove the texture connection of a TextureSample (E004).
    let id = AssetId::new(AssetType::Material, "env/water");
    let mut a = shader_project::assets::load(&p, &id).unwrap();
    a.edges.retain(|e| !(e.to.1 == "tex"));
    ops::save(&p, &id, &a).unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(r.assets[&id].diagnostics.iter().any(|d| d.code == Code::E004));
    assert_eq!(old, read(&p.root.join("assets/shaders/autogen/env/water.wesl")));
    // The Rust module of the broken material is kept and still registered.
    assert!(p.root.join("crates/shaders/src/materials/env/water.rs").exists());
    assert!(read(&p.root.join("crates/shaders/src/materials/env/mod.rs")).contains("pub mod water;"));
    assert!(!r.assets[&AssetId::new(AssetType::Material, "env/rock_wet")].diagnostics.iter().any(|d| d.is_error()));
}

#[test]
fn workspace_warning_w105() {
    let (_d, p) = temp_project();
    assert!(p.workspace_warning().is_none());
    std::fs::write(p.root.join("Cargo.toml"), "[workspace]\nmembers = [\"game\"]\n").unwrap();
    let w = p.workspace_warning().unwrap();
    assert_eq!(w.code, Code::W105);
    assert!(w.message.contains("crates/shaders"));
}
