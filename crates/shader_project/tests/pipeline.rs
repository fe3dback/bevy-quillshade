#[test]
fn named_routes_teleport_wires() {
    use shader_graph_core::consts::NoConsts;
    use shader_graph_core::ir::build_ir;
    use shader_graph_core::model::{Asset, AssetKind, MaterialKind, Node, PbrSettings};
    use shader_graph_core::registry::{NoCurves, NoFunctions, NoGradients, NoTextures};
    use shader_graph_core::{Value, ir::Ir};

    let reg = shader_stdlib::registry();
    let base = || {
        let mut a = Asset::new("m", AssetKind::Material(MaterialKind::Pbr3d(PbrSettings::default())));
        a.nodes.insert("out".into(), Node::new("output::Pbr3d", (0.0, 0.0)));
        let mut c = Node::new("stdlib::Constant3Vector", (0.0, 0.0));
        c.params.insert("value".into(), Value::Float3([0.25, 0.5, 0.75]));
        a.nodes.insert("c".into(), c);
        a
    };
    let ir = |a: &Asset| -> (Option<Ir>, Vec<Code>) {
        let r = build_ir(a, "m", &reg, &NoFunctions, &NoCurves, &NoConsts, &NoTextures, &NoGradients);
        (r.ir, r.diagnostics.iter().map(|d| d.code).collect())
    };

    let mut direct = base();
    direct.connect(("c", "out"), ("out", "base_color"));
    let (want, codes) = ir(&direct);
    assert!(codes.is_empty(), "{codes:?}");

    // c → [Named Route "tint"] … [Usage] → base_color: the same expression reaches the output.
    let mut routed = base();
    let mut decl = Node::new("stdlib::NamedRoute", (0.0, 0.0));
    decl.params.insert("name".into(), Value::Str("tint".into()));
    routed.nodes.insert("r".into(), decl);
    let mut usage = Node::new("stdlib::NamedRouteUsage", (0.0, 0.0));
    usage.params.insert("route".into(), Value::Str("r".into()));
    routed.nodes.insert("u".into(), usage);
    routed.connect(("c", "out"), ("r", "in"));
    routed.connect(("u", "out"), ("out", "base_color"));
    let (got, codes) = ir(&routed);
    assert!(codes.is_empty(), "{codes:?}");
    assert_eq!(got.unwrap().main.outputs["base_color"], want.unwrap().main.outputs["base_color"]);
    // The implicit edge is not stored.
    assert_eq!(routed.edges.len(), 2);

    // A usage without a declaration: E004.
    let mut dangling = routed.clone();
    dangling.nodes.remove("r");
    dangling.edges.retain(|e| e.to.0 != "r");
    assert!(ir(&dangling).1.contains(&Code::E004));

    // A loop through the route: E002.
    let mut cyclic = routed.clone();
    cyclic.nodes.insert("m".into(), Node::new("stdlib::Multiply", (0.0, 0.0)));
    cyclic.edges.retain(|e| e.to.0 != "r");
    cyclic.connect(("u", "out"), ("m", "a"));
    cyclic.connect(("m", "out"), ("r", "in"));
    assert!(ir(&cyclic).1.contains(&Code::E002));
}

#[test]
fn curves_generate_rename_and_report_missing() {
    let (_d, p) = temp_project();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(!r.has_errors(), "{:?}", r.diagnostics().collect::<Vec<_>>());
    let pulse = p.root.join("assets/quillshade/material/autogen/curves/dir_common/crv_pulse.wesl");
    assert!(read(&pulse).contains("fn sample_curve_catmullrom(t: f32) -> f32"));
    let bands = p.root.join("assets/quillshade/material/autogen/dir_fx/mat_curve_bands.wesl");
    let before = read(&bands);

    // Editing a curve rewrites only its own module.
    let id = AssetId::new(AssetType::Curve, "common/pulse");
    let edited = shader_graph_core::Curve::new("pulse", vec![(0.0, 1.0), (1.0, 0.0)]);
    ops::save_curve(&p, &id, &edited).unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    let changed: Vec<String> = r.changes.iter().map(|c| p.rel(c.path())).collect();
    assert_eq!(changed.len(), 1, "{changed:?}");
    assert!(changed[0].contains("curves/dir_common/crv_pulse.wesl"), "{changed:?}");
    assert_eq!(read(&bands), before);

    // Renaming follows the users; the old module becomes an orphan.
    ops::rename(&p, &id, "ramps/pulse").unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    assert!(!r.has_errors(), "{:?}", r.diagnostics().collect::<Vec<_>>());
    assert!(read(&bands).contains("import super::super::curves::dir_ramps::crv_pulse::sample_curve_catmullrom as"));
    assert!(!pulse.exists());

    // A deleted curve leaves E006 at the node that samples it; the rest of the project still generates.
    ops::delete(&p, &AssetId::new(AssetType::Curve, "ramps/pulse")).unwrap();
    let r = regenerate(&p, &RegenOptions::default()).unwrap();
    let errors: Vec<_> = r.diagnostics().filter(|d| d.is_error()).collect();
    assert_eq!(errors.len(), 1, "{errors:?}");
    assert_eq!(errors[0].code, Code::E006);
    assert_eq!(errors[0].asset.as_deref(), Some("quillshade/material/fx/curve_bands.material.ron"));
    assert!(errors[0].node.is_some());
    assert!(bands.exists(), "a broken material keeps its previous output");
}

