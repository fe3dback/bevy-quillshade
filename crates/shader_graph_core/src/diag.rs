//! Validation diagnostics with stable codes (spec §13).

use std::fmt;

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum Code {
    /// Missing or duplicated `MaterialOutput`/`FunctionOutput`.
    E001,
    /// Cycle in the graph.
    E002,
    /// Incompatible pin types without an allowed conversion.
    E003,
    /// Required input is not connected.
    E004,
    /// Invalid or duplicated parameter/asset name.
    E005,
    /// Reference to a missing function or recursive function call.
    E006,
    /// `Custom` node WESL does not parse.
    E007,
    /// Autogen file without the AUTOGENERATED marker blocks writing.
    E008,
    /// Unknown node kind or malformed graph data.
    E009,
    /// Generated WESL failed to compile (should not happen).
    E010,
    /// Dead branch, excluded from codegen.
    W101,
    /// Output pin inactive for the current blend mode.
    W102,
    /// Vertex attribute that a mesh may lack.
    W103,
    /// Vector truncated by an implicit conversion.
    W104,
    /// `crates/shaders` is not listed in `[workspace.members]`.
    W105,
    /// Global constant node without a constant: outputs 1.0 / `true` (decision 0017).
    W106,
    /// Node preview active, or the stored preview ignored (decision 0022).
    W107,
    /// Node preview changes the generated Rust crate (extra parameters or builtins) (decision 0022).
    W108,
}

impl Code {
    pub fn is_error(self) -> bool {
        matches!(
            self,
            Code::E001
                | Code::E002
                | Code::E003
                | Code::E004
                | Code::E005
                | Code::E006
                | Code::E007
                | Code::E008
                | Code::E009
                | Code::E010
        )
    }
}

impl fmt::Display for Code {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct Diagnostic {
    pub code: Code,
    pub message: String,
    /// Asset path (`env/rock_wet`), filled by the project layer.
    pub asset: Option<String>,
    pub node: Option<String>,
    pub pin: Option<String>,
}

impl Diagnostic {
    pub fn new(code: Code, message: impl Into<String>) -> Self {
        Diagnostic { code, message: message.into(), asset: None, node: None, pin: None }
    }

    pub fn at_node(mut self, node: impl Into<String>) -> Self {
        self.node = Some(node.into());
        self
    }

    pub fn at_pin(mut self, pin: impl Into<String>) -> Self {
        self.pin = Some(pin.into());
        self
    }

    pub fn in_asset(mut self, asset: impl Into<String>) -> Self {
        self.asset = Some(asset.into());
        self
    }

    pub fn is_error(&self) -> bool {
        self.code.is_error()
    }
}

impl fmt::Display for Diagnostic {
    /// CI-friendly `path:node:code: text` (spec §13).
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let node = match (&self.node, &self.pin) {
            (Some(n), Some(p)) => format!("{n}.{p}"),
            (Some(n), None) => n.clone(),
            _ => "-".into(),
        };
        write!(f, "{}:{}:{}: {}", self.asset.as_deref().unwrap_or("-"), node, self.code, self.message)
    }
}

/// Collection of diagnostics with dedup.
#[derive(Debug, Clone, Default)]
pub struct Diagnostics(pub Vec<Diagnostic>);

impl Diagnostics {
    pub fn push(&mut self, d: Diagnostic) {
        if !self.0.contains(&d) {
            self.0.push(d);
        }
    }

    pub fn extend(&mut self, ds: impl IntoIterator<Item = Diagnostic>) {
        for d in ds {
            self.push(d);
        }
    }

    pub fn has_errors(&self) -> bool {
        self.0.iter().any(Diagnostic::is_error)
    }

    pub fn iter(&self) -> impl Iterator<Item = &Diagnostic> {
        self.0.iter()
    }

    pub fn into_vec(self) -> Vec<Diagnostic> {
        self.0
    }
}
