//! Material's steps of Help → Quick Start (design §8.2): from the generated crate hooked into the game (core's steps
//! before these) to a material on screen (README "Hooking it up to a game"); core draws the dialog, the step tabs and
//! headings ([`QuickStartDef`]).

use bevy::prelude::*;

use crate::ui::{TEXT, TEXT_DIM, text};
use editor_core::domain::{Highlighter, QuickStartDef};
use editor_core::ui::welcome::code;

/// Material's Quick Start ([`crate::domain::MaterialDomain`] registers it).
pub const QUICK_START: QuickStartDef = QuickStartDef { steps: &QUICK_START_STEPS, body: step_body };

/// Material's steps after core's (the generated crate in Cargo.toml, `QuillshadePlugin`), one tab per step: (title,
/// optional); the dialog titles them "Material: …".
pub const QUICK_START_STEPS: [(&str, bool); 4] =
    [("Files", false), ("Spawn", false), ("Loading", true), ("Hot reload", false)];

/// One block of a Quick Start step.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Block {
    /// A paragraph.
    Para(&'static str),
    /// A dimmed remark.
    Note(&'static str),
    /// A code snippet.
    Code(&'static str, CodeLang),
}

/// The lines of step `step` below its heading.
fn step_body(step: usize) -> Vec<Box<dyn Scene>> {
    step_blocks(step)
        .into_iter()
        .map(|b| -> Box<dyn Scene> {
            match b {
                Block::Para(s) => Box::new(text(s, TEXT, 13.0)),
                Block::Note(s) => Box::new(text(s, TEXT_DIM, 12.0)),
                Block::Code(s, lang) => Box::new(code(s, lang.highlighter())),
            }
        })
        .collect()
}

/// Every text of step `step` (paragraphs, notes and code), in order.
#[cfg(test)]
fn step_texts(step: usize) -> Vec<&'static str> {
    let text = |b| match b {
        Block::Para(s) | Block::Note(s) | Block::Code(s, _) => s,
    };
    step_blocks(step).into_iter().map(text).collect()
}

fn step_blocks(step: usize) -> Vec<Block> {
    let (p, note) = (Block::Para, Block::Note);
    let c = |s: &'static str| Block::Code(s, CodeLang::Plain);
    let rs = |s: &'static str| Block::Code(s, CodeLang::Rust);
    match step {
        0 => vec![
            p("Material's files in the game crate (create graphs with Assets > New ... or a right click in the \
               Project tree):"),
            c("my_game/\n\
               \x20 quillshade/material/                  # your graphs: *.material.ron, *.function.ron, ...\n\
               \x20 assets/quillshade/material/autogen/   # generated WESL + baked.ron (do not edit)\n\
               \x20 assets/quillshade/material/internal/  # built-in textures (generated)\n\
               \x20 crates/quillshade/src/material/       # generated material types (do not edit)"),
            note("Generated files carry an AUTOGENERATED marker; a file without it is never overwritten (E008)."),
        ],
        1 => vec![
            p("QuillshadePlugin registers every generated material type, reserves a handle per material \
               (BakedMaterials) and loads the baked values and textures. Every material is a field of the \
               BakedMaterials resource, by its path under quillshade/material/ \
               (quillshade/material/env/rock_wet.material.ron is baked.env.rock_wet). The handles exist from the \
               start; the materials appear behind them on their own, with the values set in the graph."),
            rs("use quillshade::material::BakedMaterials;\n\n\
               // .add_systems(Startup, spawn) next to QuillshadePlugin\n\
               fn spawn(mut commands: Commands, mut meshes: ResMut<Assets<Mesh>>, baked: Res<BakedMaterials>) {\n\
               \x20   // Pbr3d needs tangents for a Normal input.\n\
               \x20   let sphere = Sphere::new(1.0).mesh().uv(48, 24).with_generated_tangents().unwrap();\n\
               \x20   commands.spawn((Mesh3d(meshes.add(sphere)), MeshMaterial3d(baked.env.rock_wet.clone())));\n\
               \x20   commands.spawn((Camera3d::default(), Transform::from_xyz(0.0, 1.0, 4.0)));\n\
               }\n\n\
               // Unlit3d: MeshMaterial3d(baked.fx.hologram.clone()) as well.\n\
               // Sprite2d: (Sprite::from_image(image), SpriteMaterial(baked.ui.dissolve.clone())).\n\
               // By id, e.g. from your own asset data (None for an unknown id or another type):\n\
               // baked.get::<RockWetMaterial>(\"env/rock_wet\"), tex.get(\"textures/rock_albedo\")."),
            note(
                "To change a value, edit the graph: the game picks it up (Hot reload). The material constructors \
                  are internal to the generated crate.",
            ),
        ],
        2 => vec![
            p("Loading starts on its own in the first frame. Call load() in Startup yourself to use BakedTextures \
               there (every Texture asset by path: tex.textures.sprite) or to show a loading screen:"),
            rs("use quillshade::material::{\n\
               \x20   BakedMaterialsLoader, BakedMaterialsProgress, BakedMaterialsReady, BakedTextures,\n\
               };\n\n\
               // .add_systems(Startup, (load, spawn).chain()).add_systems(Update, loading_screen)\n\
               fn load(mut loader: BakedMaterialsLoader) {\n\
               \x20   let textures = loader.load(); // idempotent; fills BakedTextures at once\n\
               \x20   info!(\"loading {textures} textures\");\n\
               }\n\n\
               fn spawn(mut commands: Commands, tex: Res<BakedTextures>) {\n\
               \x20   commands.spawn(Sprite::from_image(tex.textures.sprite.clone()));\n\
               }\n\n\
               fn loading_screen(\n\
               \x20   mut progress: MessageReader<BakedMaterialsProgress>,\n\
               \x20   mut ready: MessageReader<BakedMaterialsReady>,\n\
               ) {\n\
               \x20   for p in progress.read() {\n\
               \x20       info!(\"{} / {} textures ({} failed)\", p.loaded + p.failed, p.total, p.failed);\n\
               \x20   }\n\
               \x20   if ready.read().next().is_some() {\n\
               \x20       info!(\"all textures loaded\");\n\
               \x20   }\n\
               }"),
            note(
                "Materials render before that: Bevy shows each one once its images are in. A texture that fails to \
                  load is replaced by the built-in default texture.",
            ),
        ],
        _ => vec![
            p("Run the game with file_watcher and keep the editor open: every save rewrites the generated files \
               and the game reloads them without a restart."),
            c("cd my_game && cargo run"),
            p("Reloaded live: the shader code, parameter values, the texture of a parameter, a Texture asset pointed \
               at another file, sampler settings."),
            p("Need a rebuild (cargo run again): a new / removed / renamed material or parameter, a changed \
               material kind or blend settings, sRGB / Expand grayscale of a Texture asset, new BakedTextures fields."),
            note("Out-of-sync values keep the compiled ones and log \"rebuild the game\" once."),
        ],
    }
}

/// How a [`code`] block is coloured.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum CodeLang {
    /// One colour (TOML, shell, directory trees).
    Plain,
    /// The generated-Rust tab's lexer and colours.
    Rust,
}

impl CodeLang {
    /// Rust goes through the generated-Rust tab's lexer and colours.
    fn highlighter(self) -> Option<Highlighter> {
        match self {
            CodeLang::Plain => None,
            CodeLang::Rust => Some(editor_core::highlight::highlight_rust),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use editor_core::ui::welcome::code_spans;

    /// The crate and plugin steps are core's (design §8.2): Material's start with its files.
    #[test]
    fn quick_start_has_four_steps() {
        assert_eq!(QUICK_START_STEPS.len(), 4);
        assert!(QUICK_START_STEPS.iter().all(|(title, _)| !title.contains("Material")), "{QUICK_START_STEPS:?}");
        for step in 0..QUICK_START_STEPS.len() {
            assert!(!step_texts(step).is_empty(), "step {step} has a body");
        }
    }

    #[test]
    fn quick_start_has_no_cli_commands() {
        for step in 0..QUICK_START_STEPS.len() {
            for t in step_texts(step) {
                for banned in ["regen", "check --compile", "Game Assets"] {
                    assert!(!t.contains(banned), "step {step} mentions {banned:?}: {t}");
                }
            }
        }
    }

    /// Every code block is coloured as its step data tags it: a Rust block through the lexer (several colours), a
    /// plain one (TOML, shell, directory trees) as one span.
    #[test]
    fn quick_start_rust_snippets_are_highlighted() {
        let mut rust = 0;
        for step in 0..QUICK_START_STEPS.len() {
            for b in step_blocks(step) {
                let Block::Code(s, lang) = b else { continue };
                let colours: Vec<Color> = code_spans(s, lang.highlighter()).into_iter().map(|(_, c)| c).collect();
                match lang {
                    CodeLang::Rust => {
                        rust += 1;
                        assert!(colours.iter().any(|c| *c != TEXT), "step {step}: not highlighted: {s}");
                    }
                    CodeLang::Plain => assert_eq!(colours, vec![TEXT], "step {step}: one plain span: {s}"),
                }
            }
        }
        assert!(rust > 0, "the Quick Start shows Rust code");
    }
}
