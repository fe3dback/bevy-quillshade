/// Marker that identifies files owned by the editor (spec §5).
pub const MARKER: &str = "// AUTOGENERATED by shader-editor v";

/// Generated file with a line → node map for error back-references.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct Generated {
    pub text: String,
    /// 1-based line number → node id.
    pub line_nodes: Vec<(usize, NodeId)>,
}

impl Generated {
    pub fn node_at_line(&self, line: usize) -> Option<&str> {
        self.line_nodes.iter().find(|(l, _)| *l == line).map(|(_, n)| n.as_str())
    }
}

/// Context needed besides the IR: signatures of called functions and the source file name.
pub struct GenCtx<'a> {
    pub functions: &'a BTreeMap<String, FunctionSig>,
    /// Project-relative source file (`shaders/env/rock_wet.material.ron`).
    pub source_file: &'a str,
}

/// Header line with the do-not-edit marker.
pub fn header(source: &str) -> String {
    format!("{MARKER}{GENERATOR_VERSION} from {source} — do not edit")
}

pub fn is_autogen(text: &str) -> bool {
    text.lines().next().is_some_and(|l| l.starts_with(MARKER) && l.contains("do not edit"))
}

#[derive(Default)]
struct Writer {
    lines: Vec<String>,
    map: Vec<(usize, NodeId)>,
}

impl Writer {
    fn line(&mut self, s: impl Into<String>) {
        self.lines.push(s.into());
    }

    fn node_line(&mut self, node: &str, s: impl Into<String>) {
        self.lines.push(s.into());
        self.map.push((self.lines.len(), node.to_string()));
    }

    fn blank(&mut self) {
        if self.lines.last().is_some_and(|l| !l.is_empty()) {
            self.lines.push(String::new());
        }
    }

    fn finish(mut self) -> Generated {
        while self.lines.last().is_some_and(|l| l.is_empty()) {
            self.lines.pop();
        }
        let mut text = self.lines.join("\n");
        text.push('\n');
        Generated { text, line_nodes: self.map }
    }
}

/// Collected `import` statements: module path → items.
#[derive(Default)]
struct Imports {
    items: BTreeMap<String, BTreeSet<String>>,
}

impl Imports {
    fn add(&mut self, module: &str, item: &str) {
        self.items.entry(module.to_string()).or_default().insert(item.to_string());
    }

    fn write(&self, w: &mut Writer) {
        for (m, items) in &self.items {
            let list: Vec<&str> = items.iter().map(String::as_str).collect();
            if list.len() == 1 {
                w.line(format!("import {m}::{};", list[0]));
            } else {
                w.line(format!("import {m}::{{{}}};", list.join(", ")));
            }
        }
    }
}

/// Adds stdlib and project function imports relative to module `this`.
fn graph_imports(ir: &Ir, extra_stdlib: &[(&str, &str)], this: &[String], ctx: &GenCtx, imports: &mut Imports) {
    let mut stdlib: BTreeSet<(String, String)> = ir.stdlib.clone();
    for (m, f) in extra_stdlib {
        stdlib.insert((m.to_string(), f.to_string()));
    }
    for (module, func) in &stdlib {
        if module == shader_stdlib::SPRITE_MODULE {
            imports.add("bevy_sprite_render::sprite_mesh::functions", func);
        } else {
            imports.add(&paths::relative(this, &paths::stdlib_module(module)), func);
        }
    }
    for (path, interp) in &ir.curves {
        let m = paths::relative(this, &paths::curve_module(path));
        imports.add(&m, &format!("{} as {}", interp.wesl_fn(), curve_fn_alias(path, *interp)));
    }
    for path in &ir.functions {
        let Some(sig) = ctx.functions.get(path) else { continue };
        let m = paths::relative(this, &paths::function_module(path));
        imports.add(&m, &function_ident(&sig.name));
        if sig.outputs.len() > 1 {
            imports.add(&m, &sig.out_struct());
        }
    }
}

fn write_lines(w: &mut Writer, stage: &IrStage, indent: &str) {
    for l in &stage.lines {
        w.node_line(&l.node, format!("{indent}let {}: {} = {};", l.name, l.ty, l.expr));
    }
}

fn write_custom_fns(w: &mut Writer, ir: &Ir) {
    for (name, code) in &ir.custom_fns {
        let node = name.strip_prefix("sg_custom_").unwrap_or("");
        w.blank();
        for l in code.lines() {
            if node.is_empty() {
                w.line(l);
            } else {
                w.node_line(node, l);
            }
        }
    }
}

/// Material uniform struct + texture bindings (100, then [`Ir::textures`]: 101/102, …). Field and parameter texture
/// names are `inp_*` (decision 0020), fixed textures `ft_*` (design §1.3), gradient collections `gc_*` (gradient
/// design §7; one per collection, owned by no node).
fn write_bindings(w: &mut Writer, ir: &Ir) {
    let struct_name = params_struct(&ir.name);
    if !ir.uniform.is_empty() {
        let fields: Vec<String> = ir.uniform.fields.iter().map(|f| format!("{}: {}", f.name, f.ty.wesl())).collect();
        w.line(format!("struct {struct_name} {{ {} }}", fields.join(", ")));
        w.line(
            "@group(constants::MATERIAL_BIND_GROUP) @binding(100) var<uniform> params: ".to_string()
                + &struct_name
                + ";",
        );
    }
    for t in &ir.textures {
        let node = match &t.source {
            TextureSource::Param(name) => ir.params.iter().find(|p| &p.name == name).map(|p| p.node.as_str()),
            TextureSource::Fixed { node, origin: None } => Some(node.as_str()),
            TextureSource::Fixed { origin: Some(_), .. } | TextureSource::Gradient(_) => None,
        };
        let (b, tex) = (t.binding, &t.ident);
        for l in [
            format!("@group(constants::MATERIAL_BIND_GROUP) @binding({b}) var {tex}: texture_2d<f32>;"),
            format!("@group(constants::MATERIAL_BIND_GROUP) @binding({}) var {tex}_sampler: sampler;", b + 1),
        ] {
            match node {
                Some(n) => w.node_line(n, l),
                None => w.line(l),
            }
        }
    }
}

/// Layout guard (decision 0029): compiles only with the feature the game's material enables
/// ([`Ir::layout_feature`]), so a hot-reloaded shader with other bindings fails to compile instead of crashing the
/// renderer. The unresolved identifier names the fix in Bevy's shader error.
fn write_layout_guard(w: &mut Writer, ir: &Ir) {
    w.line("// The game's compiled material enables this feature; after a change of parameters, texture bindings,");
    w.line("// World Position Offset, blend mode, two-sided or shading the shader stops compiling here until the game");
    w.line("// is rebuilt.");
    w.line(format!("@if(!{})", ir.layout_feature()));
    w.line("const_assert material_layout_changed__rebuild_the_game;");
}

/// Name of the uniform struct (`RockWetParams`), shared with the Rust generator.
pub fn params_struct(name: &str) -> String {
    format!("{}Params", to_pascal_case(name))
}

const IDENTITY4: &str = "mat4x4<f32>(vec4<f32>(1.0, 0.0, 0.0, 0.0), vec4<f32>(0.0, 1.0, 0.0, 0.0), vec4<f32>(0.0, 0.0, 1.0, 0.0), vec4<f32>(0.0, 0.0, 0.0, 1.0))";

#[derive(Clone, Copy, PartialEq)]
enum Ctx {
    Pbr,
    Unlit,
    Sprite,
    Vertex3d,
}

/// Statements defining each used builtin in a material entry point.
fn builtin_prelude(ctx: Ctx, builtins: &BTreeSet<Builtin>, imports: &mut Imports, w: &mut Writer) {
    let is3d = ctx != Ctx::Sprite;
    let view_mod =
        if is3d { "bevy_pbr::render::mesh_view_bindings" } else { "bevy_sprite_render::mesh2d::view_bindings" };
    let mesh_fns = if is3d { "bevy_pbr::render::mesh_functions" } else { "bevy_sprite_render::mesh2d::functions" };
    // Guard for fields that the prepass `VertexOutput` only has with a normal/deferred prepass.
    let tangent_guard = match ctx {
        Ctx::Pbr => "VERTEX_TANGENTS && (!PREPASS_PIPELINE || NORMAL_PREPASS_OR_DEFERRED_PREPASS)",
        _ => "VERTEX_TANGENTS",
    };
    let src = if ctx == Ctx::Vertex3d { "vertex" } else { "in" };
    for b in builtins {
        let v = b.var();
        let ty = b.wesl_type();
        match b {
            Builtin::Uv0 if ctx == Ctx::Sprite => w.line(format!("    let {v}: {ty} = in.uv;")),
            Builtin::Uv0 | Builtin::Uv1 => {
                let (flag, field) = if *b == Builtin::Uv0 { ("VERTEX_UVS_A", "uv") } else { ("VERTEX_UVS_B", "uv_b") };
                w.line(format!("    var {v}: {ty} = vec2<f32>(0.0);"));
                if ctx == Ctx::Sprite {
                    // mesh2d has a single UV channel.
                    w.line(format!("    {v} = in.uv;"));
                } else {
                    w.line(format!("    @if({flag}) {v} = {src}.{field};"));
                }
            }
            Builtin::WorldPosition => {
                let e = if ctx == Ctx::Vertex3d { "out.world_position.xyz" } else { "in.world_position.xyz" };
                w.line(format!("    let {v}: {ty} = {e};"));
            }
            Builtin::WorldNormal => {
                let e = match ctx {
                    Ctx::Pbr => "pbr_input.world_normal",
                    Ctx::Vertex3d => "out.world_normal",
                    _ => "normalize(in.world_normal)",
                };
                w.line(format!("    let {v}: {ty} = {e};"));
            }
            Builtin::WorldTangent => {
                w.line(format!("    var {v}: {ty} = vec4<f32>(1.0, 0.0, 0.0, 1.0);"));
                let e = if ctx == Ctx::Vertex3d { "out.world_tangent" } else { "in.world_tangent" };
                w.line(format!("    @if({tangent_guard}) {v} = {e};"));
            }
            Builtin::VertexColor => {
                w.line(format!("    var {v}: {ty} = vec4<f32>(1.0);"));
                w.line(format!("    @if(VERTEX_COLORS) {v} = {src}.color;"));
            }
            Builtin::FragCoord => {
                let e = if ctx == Ctx::Vertex3d { "vec4<f32>(0.0)" } else { "in.position" };
                w.line(format!("    let {v}: {ty} = {e};"));
            }
            Builtin::Time | Builtin::DeltaTime => {
                let field = if *b == Builtin::Time { "time" } else { "delta_time" };
                imports.add(view_mod, "globals");
                if ctx == Ctx::Pbr {
                    // The prepass/deferred pipeline binds globals at binding 1 (main pass: 11).
                    imports.add("bevy_render::globals", "Globals");
                    w.line(format!("    var {v}: {ty} = 0.0;"));
                    w.line(format!("    @if(PREPASS_PIPELINE) {{ {v} = sg_prepass_globals.{field}; }} @else {{ {v} = globals.{field}; }}"));
                } else {
                    w.line(format!("    let {v}: {ty} = globals.{field};"));
                }
            }
            Builtin::ViewSize | Builtin::CameraPosition | Builtin::ViewFromWorld | Builtin::ClipFromWorld => {
                imports.add(view_mod, "view");
                let e = match b {
                    Builtin::ViewSize => "view.viewport.zw",
                    Builtin::CameraPosition => "view.world_position",
                    Builtin::ViewFromWorld => "view.view_from_world",
                    _ => "view.clip_from_world",
                };
                w.line(format!("    let {v}: {ty} = {e};"));
            }
            Builtin::WorldFromLocal => match ctx {
                Ctx::Vertex3d => w.line(format!("    let {v}: {ty} = world_from_local;")),
                Ctx::Sprite => {
                    imports.add(mesh_fns, "get_world_from_local");
                    w.line(format!("    let {v}: {ty} = get_world_from_local(in.instance_index);"));
                }
                _ => {
                    imports.add(mesh_fns, "get_world_from_local");
                    w.line(format!("    var {v}: {ty} = {IDENTITY4};"));
                    w.line(format!(
                        "    @if(VERTEX_OUTPUT_INSTANCE_INDEX) {v} = get_world_from_local(in.instance_index);"
                    ));
                }
            },
        }
    }
}

/// Whether the material uses prepass globals (needs the extra binding declaration).
fn uses_time(builtins: &BTreeSet<Builtin>) -> bool {
    builtins.contains(&Builtin::Time) || builtins.contains(&Builtin::DeltaTime)
}

/// Generates the WESL file of a material.
pub fn material(ir: &Ir, ctx: &GenCtx) -> Generated {
    let kind = *ir.kind.material().expect("material IR");
    let this = paths::material_module(&ir.path);
    let mut w = Writer::default();
    let mut imports = Imports::default();
    w.line(header(ctx.source_file));
    w.line(format!("// bevy 0.20, stdlib v{}", shader_stdlib::STDLIB_VERSION));
    if let Some(p) = &ir.preview {
        w.line(format!("// preview of node {} ({}): the material output is bypassed", p.node, p.mode.label()));
    }

    let normal = ir.main.outputs.contains_key("normal") && matches!(kind, MaterialKind::Pbr3d(_));
    let extra: Vec<(&str, &str)> = if normal { vec![("transform", "sg_tbn")] } else { vec![] };
    graph_imports(ir, &extra, &this, ctx, &mut imports);

    // Body first (it registers builtin imports), header assembled afterwards.
    let mut body = Writer::default();
    match kind {
        MaterialKind::Pbr3d(_) => pbr_fragment(ir, &kind, normal, &mut imports, &mut body),
        MaterialKind::Unlit3d(_) => unlit_fragment(ir, &kind, &mut imports, &mut body),
        MaterialKind::Sprite2d(_) => sprite_fragment(ir, &mut imports, &mut body),
    }
    if let Some(vs) = &ir.vertex {
        vertex_3d(vs, matches!(kind, MaterialKind::Pbr3d(_)), &mut imports, &mut body);
    }

    match kind {
        MaterialKind::Pbr3d(_) => {
            w.line("import bevy_pbr::render::{pbr_fragment::pbr_input_from_standard_material, pbr_functions::alpha_discard};");
            w.line("@if(PREPASS_PIPELINE)");
            w.line(
                "import bevy_pbr::{prepass::io::{VertexOutput, FragmentOutput}, deferred::functions::deferred_output};",
            );
            w.line("@else");
            w.line("import bevy_pbr::render::{forward_io::{VertexOutput, FragmentOutput}, pbr_functions::{apply_pbr_lighting, main_pass_post_lighting_processing}};");
        }
        MaterialKind::Unlit3d(_) => {
            imports.add("bevy_pbr::render::forward_io", "VertexOutput");
        }
        MaterialKind::Sprite2d(_) => {
            imports.add("bevy_sprite_render::mesh2d::vertex_output", "VertexOutput");
            imports.add("bevy_sprite_render::sprite_mesh::functions", "get_final_color");
            imports.add("bevy_sprite_render::sprite_mesh::functions", "sample_final_color");
        }
    }
    if ir.vertex.is_some() {
        let guard = if matches!(kind, MaterialKind::Pbr3d(_)) { "@if(!PREPASS_PIPELINE)\n" } else { "" };
        w.line(format!(
            "{guard}import bevy_pbr::render::{{mesh_bindings::mesh, mesh_functions, skinning, morph, forward_io::{{Vertex, UncompressedVertex, decompress_vertex}}, view_transformations::position_world_to_clip}};"
        ));
    }
    imports.write(&mut w);
    w.blank();

    write_bindings(&mut w, ir);
    write_layout_guard(&mut w, ir);
    if matches!(kind, MaterialKind::Pbr3d(_)) && uses_time(&ir.main.builtins) {
        w.line("@if(PREPASS_PIPELINE) @group(0) @binding(1) var<uniform> sg_prepass_globals: Globals;");
    }
    write_custom_fns(&mut w, ir);
    w.blank();

    // Append body with line numbers shifted.
    let offset = w.lines.len();
    for (l, n) in body.map {
        w.map.push((l + offset, n));
    }
    w.lines.extend(body.lines);
    w.finish()
}

fn pbr_fragment(ir: &Ir, kind: &MaterialKind, normal: bool, imports: &mut Imports, w: &mut Writer) {
    let o = &ir.main.outputs;
    let blend = kind.blend();
    w.line("@fragment");
    w.line("fn fragment(in: VertexOutput, @builtin(front_facing) is_front: bool) -> FragmentOutput {");
    w.line("    var pbr_input = pbr_input_from_standard_material(in, is_front);");
    if !ir.main.builtins.is_empty() {
        w.line("    // --- builtins ---");
        builtin_prelude(Ctx::Pbr, &ir.main.builtins, imports, w);
    }
    if !ir.main.lines.is_empty() {
        w.line("    // --- graph ---");
        write_lines(w, &ir.main, "    ");
    }
    w.line("    // --- outputs ---");
    if let Some(v) = o.get("base_color") {
        // Node preview forces alpha to 1 (decision 0022).
        let alpha = if ir.preview.is_some() { "1.0" } else { "pbr_input.material.base_color.a" };
        w.line(format!("    pbr_input.material.base_color = vec4<f32>({v}, {alpha});"));
    }
    if let Some(v) = o.get("metallic") {
        w.line(format!("    pbr_input.material.metallic = {v};"));
    }
    if let Some(v) = o.get("specular") {
        w.line(format!("    pbr_input.material.reflectance = vec3<f32>({v});"));
    }
    if let Some(v) = o.get("roughness") {
        w.line(format!("    pbr_input.material.perceptual_roughness = {v};"));
    }
    if let Some(v) = o.get("emissive") {
        w.line(format!("    pbr_input.material.emissive = vec4<f32>({v}, pbr_input.material.emissive.a);"));
    }
    match blend {
        BlendMode::Mask => {
            if let Some(v) = o.get("opacity_mask") {
                w.line(format!("    pbr_input.material.base_color.a = {v};"));
            }
        }
        BlendMode::Opaque => {}
        _ => {
            if let Some(v) = o.get("opacity") {
                w.line(format!("    pbr_input.material.base_color.a = {v};"));
            }
        }
    }
    if let Some(v) = o.get("ambient_occlusion") {
        w.line(format!("    pbr_input.diffuse_occlusion = pbr_input.diffuse_occlusion * {v};"));
    }
    if normal && let Some(v) = o.get("normal") {
        w.line("    @if(VERTEX_TANGENTS && (!PREPASS_PIPELINE || NORMAL_PREPASS_OR_DEFERRED_PREPASS)) {");
        w.line(format!("        pbr_input.N = normalize(sg_tbn(pbr_input.world_normal, in.world_tangent) * {v});"));
        w.line("    }");
    }
    // Unlit preview bypasses lighting in WESL only (spec §5), like Bevy's `pbr.wesl` does for unlit materials:
    // the flag also reaches the deferred G-buffer through `deferred_output`.
    let unlit_preview = ir.preview.as_ref().is_some_and(|p| p.mode == PreviewMode::Unlit);
    if unlit_preview {
        imports.add("bevy_pbr::render::pbr_types", "STANDARD_MATERIAL_FLAGS_UNLIT_BIT");
        w.line("    pbr_input.material.flags = pbr_input.material.flags | STANDARD_MATERIAL_FLAGS_UNLIT_BIT;");
    }
    w.line("    pbr_input.material.base_color = alpha_discard(pbr_input.material.flags, pbr_input.material.alpha_cutoff, pbr_input.material.base_color);");
    w.line("    var out: FragmentOutput;");
    w.line("    @if(PREPASS_PIPELINE) {");
    w.line("        out = deferred_output(in, pbr_input);");
    w.line("    } @else {");
    if unlit_preview {
        w.line("        out.color = pbr_input.material.base_color;");
    } else {
        w.line("        out.color = apply_pbr_lighting(pbr_input);");
    }
    w.line("        out.color = main_pass_post_lighting_processing(pbr_input, out.color);");
    w.line("    }");
    w.line("    return out;");
    w.line("}");
}

/// Alpha cutoff of `Mask` blend mode (UE default clip value).
pub const MASK_CUTOFF: f32 = 0.3333;

fn unlit_fragment(ir: &Ir, kind: &MaterialKind, imports: &mut Imports, w: &mut Writer) {
    let o = &ir.main.outputs;
    let blend = kind.blend();
    w.line("@fragment");
    w.line("fn fragment(in: VertexOutput) -> @location(0) vec4<f32> {");
    if !ir.main.builtins.is_empty() {
        w.line("    // --- builtins ---");
        builtin_prelude(Ctx::Unlit, &ir.main.builtins, imports, w);
    }
    if !ir.main.lines.is_empty() {
        w.line("    // --- graph ---");
        write_lines(w, &ir.main, "    ");
    }
    w.line("    // --- outputs ---");
    let color = o.get("color").cloned().unwrap_or_else(|| "vec3<f32>(0.0)".into());
    if ir.preview.is_some() {
        // Node preview (decision 0022): opaque color, no opacity, mask or blend-mode handling.
        w.line(format!("    return vec4<f32>({color}, 1.0);"));
        w.line("}");
        return;
    }
    let alpha = match blend {
        BlendMode::Opaque | BlendMode::Mask => "1.0".to_string(),
        _ => o.get("opacity").cloned().unwrap_or_else(|| "1.0".into()),
    };
    w.line(format!("    let color: vec3<f32> = {color};"));
    w.line(format!("    let alpha: f32 = {alpha};"));
    if blend == BlendMode::Mask
        && let Some(m) = o.get("opacity_mask")
    {
        w.line(format!("    if ({m}) < {} {{", shader_graph_core::value::wesl_f32(MASK_CUTOFF)));
        w.line("        discard;");
        w.line("    }");
    }
    match blend {
        // Additive blending in Bevy expects premultiplied color.
        BlendMode::Add => w.line("    return vec4<f32>(color * alpha, alpha);"),
        BlendMode::Multiply => w.line("    return vec4<f32>(mix(vec3<f32>(1.0), color, alpha), alpha);"),
        _ => w.line("    return vec4<f32>(color, alpha);"),
    }
    w.line("}");
}

fn sprite_fragment(ir: &Ir, imports: &mut Imports, w: &mut Writer) {
    let o = &ir.main.outputs;
    w.line("@fragment");
    w.line("fn fragment(in: VertexOutput) -> @location(0) vec4<f32> {");
    if !ir.main.builtins.is_empty() {
        w.line("    // --- builtins ---");
        builtin_prelude(Ctx::Sprite, &ir.main.builtins, imports, w);
    }
    if !ir.main.lines.is_empty() {
        w.line("    // --- graph ---");
        write_lines(w, &ir.main, "    ");
    }
    w.line("    // --- outputs ---");
    match o.get("color") {
        // Node preview (decision 0022): the IR built `vec4<f32>(albedo, 1.0)`, no sprite color/tint.
        Some(c) if ir.preview.is_some() => w.line(format!("    return {c};")),
        Some(c) => w.line(format!("    return get_final_color({c}, in.instance_index);")),
        None => {
            let uv = o.get("uv").cloned().unwrap_or_else(|| "in.uv".into());
            w.line(format!("    return sample_final_color({uv}, in.instance_index);"));
        }
    }
    w.line("}");
}

/// Forward vertex shader: Bevy's `bevy_pbr::render::mesh::vertex` plus World Position Offset.
fn vertex_3d(vs: &IrStage, pbr: bool, imports: &mut Imports, w: &mut Writer) {
    let Some(wpo) = vs.outputs.get(shader_graph_core::ir::WPO_PIN) else { return };
    w.blank();
    if pbr {
        w.line("@if(!PREPASS_PIPELINE)");
    }
    w.line("fn sg_morph_vertex(vertex_in: UncompressedVertex, instance_index: u32) -> UncompressedVertex {");
    w.line("    var vertex = vertex_in;");
    w.line("    @if(MORPH_TARGETS) {");
    w.line("        let first_vertex = mesh[instance_index].first_vertex_index;");
    w.line("        let vertex_index = vertex.index - first_vertex;");
    w.line("        let morph_descriptor_index = mesh[instance_index].morph_descriptor_index;");
    w.line("        let weight_count = morph::layer_count(morph_descriptor_index);");
    w.line("        for (var i: u32 = 0u; i < weight_count; i++) {");
    w.line("            let weight = morph::weight_at(i, morph_descriptor_index);");
    w.line("            if weight == 0.0 {");
    w.line("                continue;");
    w.line("            }");
    w.line("            vertex.position += weight * morph::morph_position(vertex_index, i, morph_descriptor_index);");
    w.line("            @if(VERTEX_NORMALS) vertex.normal += weight * morph::morph_normal(vertex_index, i, morph_descriptor_index);");
    w.line("            @if(VERTEX_TANGENTS) vertex.tangent += vec4<f32>(weight * morph::morph_tangent(vertex_index, i, morph_descriptor_index), 0.0);");
    w.line("        }");
    w.line("    }");
    w.line("    return vertex;");
    w.line("}");
    w.blank();
    if pbr {
        w.line("@if(!PREPASS_PIPELINE)");
    }
    w.line("@vertex");
    w.line("fn vertex(vertex_no_morph: Vertex) -> VertexOutput {");
    w.line("    var out: VertexOutput;");
    w.line("    let uncompressed = decompress_vertex(vertex_no_morph, vertex_no_morph.instance_index);");
    w.line("    let vertex = sg_morph_vertex(uncompressed, vertex_no_morph.instance_index);");
    w.line("    let mesh_world_from_local = mesh_functions::get_world_from_local(vertex_no_morph.instance_index);");
    w.line("    var world_from_local = mesh_world_from_local;");
    w.line("    @if(SKINNED) world_from_local = skinning::skin_model(vertex.joint_indices, vertex.joint_weights, vertex_no_morph.instance_index);");
    w.line("    @if(VERTEX_NORMALS && SKINNED) out.world_normal = skinning::skin_normals(world_from_local, vertex.normal);");
    w.line("    @if(VERTEX_NORMALS && !SKINNED) out.world_normal = mesh_functions::mesh_normal_local_to_world(vertex.normal, vertex_no_morph.instance_index);");
    w.line("    @if(VERTEX_POSITIONS) out.world_position = mesh_functions::mesh_position_local_to_world(world_from_local, vec4<f32>(vertex.position, 1.0));");
    w.line("    @if(VERTEX_UVS_A) out.uv = vertex.uv;");
    w.line("    @if(VERTEX_UVS_B) out.uv_b = vertex.uv_b;");
    w.line("    @if(VERTEX_TANGENTS) out.world_tangent = mesh_functions::mesh_tangent_local_to_world(world_from_local, vertex.tangent, vertex_no_morph.instance_index);");
    w.line("    @if(VERTEX_COLORS) out.color = vertex.color;");
    w.line("    @if(VERTEX_OUTPUT_INSTANCE_INDEX) out.instance_index = vertex_no_morph.instance_index;");
    w.line("    @if(VISIBILITY_RANGE_DITHER) out.visibility_range_dither = mesh_functions::get_visibility_range_dither_level(vertex_no_morph.instance_index, mesh_world_from_local[3]);");
    if !vs.builtins.is_empty() {
        w.line("    // --- builtins ---");
        builtin_prelude(Ctx::Vertex3d, &vs.builtins, imports, w);
    }
    if !vs.lines.is_empty() {
        w.line("    // --- graph ---");
        write_lines(w, vs, "    ");
    }
    w.line("    // --- world position offset ---");
    w.line(format!("    out.world_position = vec4<f32>(out.world_position.xyz + {wpo}, 1.0);"));
    w.line("    out.position = position_world_to_clip(out.world_position.xyz);");
    w.line("    return out;");
    w.line("}");
}

/// Generates the WESL module of a project function: `fn fun_{name}(inp_*, b_*, ft_*, gc_*)` returning the value or a
/// `{Name}Out { out_* }` struct (decision 0020).
pub fn function(ir: &Ir, ctx: &GenCtx) -> Generated {
    let sig = ir.function_sig.as_ref().expect("function IR");
    let this = paths::function_module(&ir.path);
    let mut w = Writer::default();
    let mut imports = Imports::default();
    w.line(header(ctx.source_file));
    w.line(format!("// stdlib v{}", shader_stdlib::STDLIB_VERSION));
    graph_imports(ir, &[], &this, ctx, &mut imports);
    imports.write(&mut w);
    w.blank();
    write_custom_fns(&mut w, ir);
    w.blank();

    let mut args = Vec::new();
    for i in &sig.inputs {
        let name = input_ident(&i.name);
        if i.ty == PinType::Texture2D {
            args.push(format!("{name}: texture_2d<f32>, {name}_sampler: sampler"));
        } else {
            args.push(format!("{name}: {}", i.ty.wesl()));
        }
    }
    for b in &sig.builtins {
        args.push(format!("{}: {}", b.var(), b.wesl_type()));
    }
    // Hidden fixed textures (design §1.3): `ft_{origin}_{node}` + sampler, after the builtins.
    for t in &sig.textures {
        let name = t.ident();
        args.push(format!("{name}: texture_2d<f32>, {name}_sampler: sampler"));
    }
    // Hidden gradient collections (gradient design §7): `gc_{path}` + sampler, one per collection, after the fixed
    // textures; the caller passes its own binding or hidden parameter of the same name.
    for c in &sig.gradients {
        let name = gradient_ident(c);
        args.push(format!("{name}: texture_2d<f32>, {name}_sampler: sampler"));
    }
    let ret = if sig.outputs.len() == 1 { sig.outputs[0].ty.wesl().to_string() } else { sig.out_struct() };
    if sig.outputs.len() > 1 {
        let fields: Vec<String> =
            sig.outputs.iter().map(|o| format!("{}: {}", output_ident(&o.name), o.ty.wesl())).collect();
        w.line(format!("struct {} {{ {} }}", sig.out_struct(), fields.join(", ")));
        w.blank();
    }
    w.line(format!("fn {}({}) -> {ret} {{", function_ident(&sig.name), args.join(", ")));
    write_lines(&mut w, &ir.main, "    ");
    let value = |name: &str, ty: PinType| {
        ir.main.outputs.get(name).cloned().unwrap_or_else(|| shader_graph_core::Value::zero(ty).wesl_literal(ty))
    };
    if sig.outputs.len() == 1 {
        w.line(format!("    return {};", value(&sig.outputs[0].name, sig.outputs[0].ty)));
    } else {
        let vals: Vec<String> = sig.outputs.iter().map(|o| value(&o.name, o.ty)).collect();
        w.line(format!("    return {}({});", sig.out_struct(), vals.join(", ")));
    }
    w.line("}");
    w.finish()
}

/// Generates the WESL module of a curve asset at `path` (decision 0015): the points as a const array of
/// `(t, value, slope)` and one sampling function per [`Interp`]. Values and slopes are baked in real units (the
/// output range `min..max`, decision 0038), so a curve at the default range `0..1` keeps its text.
pub fn curve(c: &Curve, path: &str, source_file: &str) -> String {
    let this = paths::curve_module(path);
    let mut w = Writer::default();
    w.line(header(source_file));
    w.line(format!("// stdlib v{}", shader_stdlib::STDLIB_VERSION));
    let n = c.points.len();
    if n >= 2 {
        let m = paths::relative(&this, &paths::stdlib_module("curve"));
        w.line(format!("import {m}::{{sg_curve_hermite, sg_curve_linear}};"));
        w.blank();
        let f = shader_graph_core::value::wesl_f32;
        w.line("// (t, value, slope) per point, sorted by t.");
        w.line(format!("const POINTS: array<vec3<f32>, {n}> = array<vec3<f32>, {n}>("));
        for ((t, v), s) in c.points.iter().zip(c.slopes()) {
            w.line(format!("    vec3<f32>({}, {}, {}),", f(*t), f(c.to_real(*v)), f(s * c.span())));
        }
        w.line(");");
        w.blank();
        w.line("// Index of the segment [POINTS[i], POINTS[i + 1]] containing `x`.");
        w.line("fn segment(x: f32) -> u32 {");
        w.line("    var i = 0u;");
        w.line(format!("    for (var k = 1u; k < {}u; k++) {{", n - 1));
        w.line("        if x >= POINTS[k].x {");
        w.line("            i = k;");
        w.line("        }");
        w.line("    }");
        w.line("    return i;");
        w.line("}");
    }
    for interp in [Interp::Simple, Interp::CatmullRom] {
        w.blank();
        w.line(format!("fn {}(t: f32) -> f32 {{", interp.wesl_fn()));
        match n {
            0 => w.line(format!("    return {};", shader_graph_core::value::wesl_scalar(c.min))),
            1 => w.line(format!("    return {};", shader_graph_core::value::wesl_scalar(c.to_real(c.points[0].1)))),
            _ => {
                let helper = if interp == Interp::Simple { "sg_curve_linear" } else { "sg_curve_hermite" };
                w.line(format!("    let x = clamp(t, POINTS[0].x, POINTS[{}].x);", n - 1));
                w.line("    let i = segment(x);");
                w.line(format!("    return {helper}(POINTS[i], POINTS[i + 1u], x);"));
            }
        }
        w.line("}");
    }
    w.finish().text
}

/// `autogen/stdlib/{name}.wesl` content.
pub fn stdlib_module(name: &str, source: &str) -> String {
    format!("{}\n// stdlib v{}\n\n{}", header(&format!("stdlib::{name}")), shader_stdlib::STDLIB_VERSION, source)
}

/// Binding of material parameter `param` (uniform block or its texture; samplers are at texture + 1), used by
/// docs and tests.
pub fn binding_of(ir: &Ir, param: &str) -> Option<u32> {
    let p = ir.params.iter().find(|p| p.name == param)?;
    if p.ty != ParamType::Texture {
        return Some(100);
    }
    ir.param_texture(param).map(|t| t.binding)
}
