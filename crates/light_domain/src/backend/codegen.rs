//! The Light module of the umbrella crate (design §9.2): `crates/quillshade/src/light/mod.rs` and
//! `assets/quillshade/light/autogen/baked.ron`.

use std::collections::BTreeMap;

use project_core::marker::header;
use serde::{Deserialize, Serialize};
use texture_kit::TextureSettings;

use super::model::{
    ColorGradingDef, ColorGradingGlobalDef, ColorGradingSectionDef, DirectionalLightDef, Environment, FogDef,
    FogFalloffDef, LightAssets, TonemappingMode, to_pascal_case,
};

const LIGHT_MOD_TEMPLATE: &str = include_str!("templates/light_mod.rs");
const BLENDED_SKYBOX_WESL: &str = include_str!("templates/blended_skybox.wesl");

/// Format version of `assets/quillshade/light/autogen/baked.ron`.
pub const MANIFEST_FORMAT_VERSION: u32 = 1;

/// One Light cube-map texture entry in `baked.ron`.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct ManifestTextureEntry {
    pub path: String,
    pub settings: TextureSettings,
}

/// One Light transition curve entry in `baked.ron`.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct ManifestCurveEntry {
    pub min: f32,
    pub max: f32,
    pub points: Vec<(f32, f32)>,
}

/// Serialized representation of `assets/quillshade/light/autogen/baked.ron`.
#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct BakedLightManifestData {
    pub format_version: u32,
    pub textures: BTreeMap<String, ManifestTextureEntry>,
    pub environments: BTreeMap<String, Environment>,
    pub curves: BTreeMap<String, ManifestCurveEntry>,
}

/// Generates `assets/quillshade/light/autogen/baked.ron` from error-free `assets`.
pub fn manifest(assets: &LightAssets) -> String {
    let textures = assets
        .textures
        .iter()
        .map(|(id, t)| (id.clone(), ManifestTextureEntry { path: t.path.clone(), settings: t.settings.clone() }))
        .collect();
    let environments = assets.environments.clone();
    let curves = assets
        .curves
        .iter()
        .map(|(id, c)| (id.clone(), ManifestCurveEntry { min: c.min, max: c.max, points: c.points.clone() }))
        .collect();

    let data = BakedLightManifestData { format_version: MANIFEST_FORMAT_VERSION, textures, environments, curves };
    let cfg = ron::ser::PrettyConfig::new()
        .struct_names(false)
        .indentor("  ".to_string())
        .new_line("\n".to_string())
        .separate_tuple_members(false);
    let body = ron::ser::to_string_pretty(&data, cfg).expect("light manifest serialization");
    format!("{}\nBakedLightManifest{body}\n", header("//", None))
}

/// Generates `crates/quillshade/src/light/mod.rs` from error-free `assets`.
pub fn module(assets: &LightAssets) -> String {
    let manifest_str = manifest(assets);
    let generated_items = emit_generated_items(assets, &manifest_str);
    format!(
        "{}\n//! Light domain generated by shader-editor: the environments and transition curves of `quillshade/light/`.\n\n{LIGHT_MOD_TEMPLATE}\n/// Embedded WESL source for the blended skybox pipeline.\npub const BLENDED_SKYBOX_WESL: &str = {BLENDED_SKYBOX_WESL:?};\n\n{generated_items}",
        header("//", None)
    )
}

fn emit_generated_items(assets: &LightAssets, manifest_str: &str) -> String {
    let mut o = String::new();

    // ENVIRONMENTS const
    o.push_str("/// Asset paths of the environments without errors (`outdoor/day`), sorted.\n");
    if assets.environments.is_empty() {
        o.push_str("pub const ENVIRONMENTS: &[&str] = &[];\n\n");
    } else {
        o.push_str("pub const ENVIRONMENTS: &[&str] = &[\n");
        for path in assets.environments.keys() {
            o.push_str(&format!("    {path:?},\n"));
        }
        o.push_str("];\n\n");
    }

    // CURVES const
    o.push_str("/// Asset paths of the transition curves without errors (`ease_in_out`), sorted.\n");
    if assets.curves.is_empty() {
        o.push_str("pub const CURVES: &[&str] = &[];\n\n");
    } else {
        o.push_str("pub const CURVES: &[&str] = &[\n");
        for path in assets.curves.keys() {
            o.push_str(&format!("    {path:?},\n"));
        }
        o.push_str("];\n\n");
    }

    // COMPILED_MANIFEST const
    o.push_str("/// Compiled snapshot of `assets/quillshade/light/autogen/baked.ron`.\n");
    o.push_str(&format!("pub const COMPILED_MANIFEST: &str = {manifest_str:?};\n\n"));

    // Preset enum
    let env_entries: Vec<(&str, String, &Environment)> =
        assets.environments.iter().map(|(path, env)| (path.as_str(), to_pascal_case(path), env)).collect();

    o.push_str("/// Lighting environment presets authored in `quillshade/light/*.environment.ron`.\n");
    if env_entries.is_empty() {
        o.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]\n");
        o.push_str("pub enum Preset {}\n\n");
    } else {
        o.push_str(
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default, Serialize, Deserialize)]\n",
        );
        o.push_str("pub enum Preset {\n");
        for (i, (path, variant, _)) in env_entries.iter().enumerate() {
            o.push_str(&format!("    /// Environment `{path}` (`quillshade/light/{path}.environment.ron`).\n"));
            if i == 0 {
                o.push_str("    #[default]\n");
            }
            o.push_str(&format!("    {variant},\n"));
        }
        o.push_str("}\n\n");
    }

    o.push_str("#[allow(unreachable_code, clippy::match_single_binding)]\n");
    o.push_str("impl Preset {\n");
    if env_entries.is_empty() {
        o.push_str("    /// All valid environment presets in path order.\n");
        o.push_str("    pub const ALL: &'static [Preset] = &[];\n\n");
        o.push_str("    /// Domain-relative asset path of this preset (`\"day\"`, `\"outdoor/sunset\"`).\n");
        o.push_str("    pub const fn as_str(self) -> &'static str {\n        match self {}\n    }\n\n");
        o.push_str("    /// Looks up a preset by its domain-relative asset path.\n");
        o.push_str("    pub fn from_path(_path: &str) -> Option<Preset> {\n        None\n    }\n\n");
        o.push_str("    /// Corresponding Bevy [`State`] variant for this preset.\n");
        o.push_str("    pub const fn state(self) -> State {\n        match self {}\n    }\n\n");
        o.push_str("    /// Compiled default [`EnvironmentValues`] for this preset.\n");
        o.push_str("    pub fn default_values(self) -> EnvironmentValues {\n        match self {}\n    }\n");
    } else {
        o.push_str("    /// All valid environment presets in path order.\n");
        o.push_str("    pub const ALL: &'static [Preset] = &[\n");
        for (_, variant, _) in &env_entries {
            o.push_str(&format!("        Self::{variant},\n"));
        }
        o.push_str("    ];\n\n");

        o.push_str("    /// Domain-relative asset path of this preset (`\"day\"`, `\"outdoor/sunset\"`).\n");
        o.push_str("    pub const fn as_str(self) -> &'static str {\n        match self {\n");
        for (path, variant, _) in &env_entries {
            o.push_str(&format!("            Self::{variant} => {path:?},\n"));
        }
        o.push_str("        }\n    }\n\n");

        o.push_str("    /// Looks up a preset by its domain-relative asset path.\n");
        o.push_str("    pub fn from_path(path: &str) -> Option<Preset> {\n        match path {\n");
        for (path, variant, _) in &env_entries {
            o.push_str(&format!("            {path:?} => Some(Self::{variant}),\n"));
        }
        o.push_str("            _ => None,\n        }\n    }\n\n");

        o.push_str("    /// Corresponding Bevy [`State`] variant for this preset.\n");
        o.push_str("    pub const fn state(self) -> State {\n        match self {\n");
        for (_, variant, _) in &env_entries {
            o.push_str(&format!("            Self::{variant} => State::{variant},\n"));
        }
        o.push_str("        }\n    }\n\n");

        o.push_str("    /// Compiled default [`EnvironmentValues`] for this preset.\n");
        o.push_str("    pub fn default_values(self) -> EnvironmentValues {\n        match self {\n");
        for (_, variant, env) in &env_entries {
            o.push_str(&format!("            Self::{variant} => {},\n", emit_env_literal(env)));
        }
        o.push_str("        }\n    }\n");
    }
    o.push_str("}\n\n");

    // Curve enum
    let curve_entries: Vec<(&str, String, &curve_kit::Curve)> =
        assets.curves.iter().map(|(path, c)| (path.as_str(), to_pascal_case(path), c)).collect();

    o.push_str("/// Transition curves authored in `quillshade/light/*.curve.ron`, plus built-in [`Curve::Linear`].\n");
    o.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Default, Serialize, Deserialize)]\n",
    );
    o.push_str("pub enum Curve {\n");
    o.push_str("    /// Built-in identity linear transition curve (`s = t`).\n");
    o.push_str("    #[default]\n");
    o.push_str("    Linear,\n");
    for (path, variant, _) in &curve_entries {
        o.push_str(&format!("    /// Curve `{path}` (`quillshade/light/{path}.curve.ron`).\n"));
        o.push_str(&format!("    {variant},\n"));
    }
    o.push_str("}\n\n");

    o.push_str("impl Curve {\n");
    o.push_str("    /// All available transition curves, starting with [`Curve::Linear`].\n");
    o.push_str("    pub const ALL: &'static [Curve] = &[\n        Self::Linear,\n");
    for (_, variant, _) in &curve_entries {
        o.push_str(&format!("        Self::{variant},\n"));
    }
    o.push_str("    ];\n\n");

    o.push_str("    /// Domain-relative asset path of this curve (`\"linear\"` for [`Curve::Linear`]).\n");
    o.push_str("    pub const fn as_str(self) -> &'static str {\n        match self {\n");
    o.push_str("            Self::Linear => \"linear\",\n");
    for (path, variant, _) in &curve_entries {
        o.push_str(&format!("            Self::{variant} => {path:?},\n"));
    }
    o.push_str("        }\n    }\n\n");

    o.push_str(
        "    /// Looks up a curve by its domain-relative asset path (`\"linear\"` returns [`Curve::Linear`]).\n",
    );
    o.push_str("    pub fn from_path(path: &str) -> Option<Curve> {\n        match path {\n");
    o.push_str("            \"linear\" => Some(Self::Linear),\n");
    for (path, variant, _) in &curve_entries {
        o.push_str(&format!("            {path:?} => Some(Self::{variant}),\n"));
    }
    o.push_str("            _ => None,\n        }\n    }\n\n");

    o.push_str("    /// Compiled default [`BakedCurve`] for this curve.\n");
    o.push_str("    pub fn default_curve(self) -> BakedCurve {\n        match self {\n");
    o.push_str("            Self::Linear => BakedCurve::linear(),\n");
    for (_, variant, curve) in &curve_entries {
        o.push_str(&format!("            Self::{variant} => {},\n", emit_curve_literal(curve)));
    }
    o.push_str("        }\n    }\n\n");

    o.push_str("    /// Evaluates the compiled curve at `t` in `0.0..=1.0`.\n");
    o.push_str("    pub fn sample(self, t: f32) -> f32 {\n        match self {\n");
    o.push_str("            Self::Linear => t.clamp(0.0, 1.0),\n");
    if !curve_entries.is_empty() {
        o.push_str("            other => other.default_curve().sample(t),\n");
    }
    o.push_str("        }\n    }\n");
    o.push_str("}\n\n");

    o.push_str("impl bevy::curve::Curve<f32> for Curve {\n");
    o.push_str("    fn domain(&self) -> bevy::curve::Interval {\n        bevy::curve::Interval::UNIT\n    }\n\n");
    o.push_str("    fn sample_unchecked(&self, t: f32) -> f32 {\n        (*self).sample(t)\n    }\n");
    o.push_str("}\n\n");

    // State enum
    o.push_str("/// Bevy [`States`] state machine tracking the active lighting preset or transition.\n");
    o.push_str("#[derive(States, Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]\n");
    o.push_str("pub enum State {\n");
    o.push_str("    /// Initial state before any lighting preset is applied.\n");
    o.push_str("    #[default]\n");
    o.push_str("    None,\n");
    o.push_str("    /// Active while a transition between two presets is in progress (`0.0 <= t < 1.0`).\n");
    o.push_str("    Transitioning,\n");
    for (path, variant, _) in &env_entries {
        o.push_str(&format!("    /// Settled on environment `{path}`.\n"));
        o.push_str(&format!("    {variant},\n"));
    }
    o.push_str("}\n\n");

    o.push_str("#[allow(unreachable_code)]\n");
    o.push_str("impl From<Preset> for State {\n");
    o.push_str("    fn from(preset: Preset) -> Self {\n        preset.state()\n    }\n");
    o.push_str("}\n\n");

    o.push_str("impl State {\n");
    o.push_str(
        "    /// Returns the settled [`Preset`] if this state corresponds to one, or `None` for [`State::None`] and\n",
    );
    o.push_str("    /// [`State::Transitioning`].\n");
    o.push_str("    pub const fn as_preset(self) -> Option<Preset> {\n        match self {\n");
    o.push_str("            Self::None | Self::Transitioning => None,\n");
    for (_, variant, _) in &env_entries {
        o.push_str(&format!("            Self::{variant} => Some(Preset::{variant}),\n"));
    }
    o.push_str("        }\n    }\n");
    o.push_str("}\n");

    o
}

fn fmt_f32(v: f32) -> String {
    if v.is_finite() { format!("{v:?}") } else { "0.0".to_string() }
}

fn fmt_arr3(a: [f32; 3]) -> String {
    format!("[{}, {}, {}]", fmt_f32(a[0]), fmt_f32(a[1]), fmt_f32(a[2]))
}

fn fmt_arr4(a: [f32; 4]) -> String {
    format!("[{}, {}, {}, {}]", fmt_f32(a[0]), fmt_f32(a[1]), fmt_f32(a[2]), fmt_f32(a[3]))
}

fn emit_curve_literal(c: &curve_kit::Curve) -> String {
    let pts: Vec<String> = c.points.iter().map(|(t, v)| format!("({}, {})", fmt_f32(*t), fmt_f32(*v))).collect();
    format!("BakedCurve {{ min: {}, max: {}, points: vec![{}] }}", fmt_f32(c.min), fmt_f32(c.max), pts.join(", "))
}

fn emit_section_literal(s: &ColorGradingSectionDef) -> String {
    format!(
        "ColorGradingSectionDef {{ saturation: {}, contrast: {}, gamma: {}, gain: {}, lift: {} }}",
        fmt_f32(s.saturation),
        fmt_f32(s.contrast),
        fmt_f32(s.gamma),
        fmt_f32(s.gain),
        fmt_f32(s.lift),
    )
}

fn emit_global_literal(g: &ColorGradingGlobalDef) -> String {
    format!(
        "ColorGradingGlobalDef {{ exposure: {}, temperature: {}, tint: {}, hue: {}, post_saturation: {}, midtones_range: [{}, {}] }}",
        fmt_f32(g.exposure),
        fmt_f32(g.temperature),
        fmt_f32(g.tint),
        fmt_f32(g.hue),
        fmt_f32(g.post_saturation),
        fmt_f32(g.midtones_range[0]),
        fmt_f32(g.midtones_range[1]),
    )
}

fn emit_color_grading_literal(cg: &ColorGradingDef) -> String {
    format!(
        "ColorGradingDef {{ global: {}, shadows: {}, midtones: {}, highlights: {} }}",
        emit_global_literal(&cg.global),
        emit_section_literal(&cg.shadows),
        emit_section_literal(&cg.midtones),
        emit_section_literal(&cg.highlights),
    )
}

fn emit_fog_literal(f: &FogDef) -> String {
    let falloff = match &f.falloff {
        FogFalloffDef::Linear { start, end } => {
            format!("FogFalloffDef::Linear {{ start: {}, end: {} }}", fmt_f32(*start), fmt_f32(*end))
        }
        FogFalloffDef::Exponential { density } => {
            format!("FogFalloffDef::Exponential {{ density: {} }}", fmt_f32(*density))
        }
        FogFalloffDef::ExponentialSquared { density } => {
            format!("FogFalloffDef::ExponentialSquared {{ density: {} }}", fmt_f32(*density))
        }
        FogFalloffDef::Atmospheric { extinction, inscattering } => format!(
            "FogFalloffDef::Atmospheric {{ extinction: {}, inscattering: {} }}",
            fmt_arr3(*extinction),
            fmt_arr3(*inscattering),
        ),
    };
    format!(
        "FogDef {{ enabled: {}, color: {}, directional_light_color: {}, directional_light_exponent: {}, falloff: {falloff} }}",
        f.enabled,
        fmt_arr4(f.color),
        fmt_arr4(f.directional_light_color),
        fmt_f32(f.directional_light_exponent),
    )
}

fn emit_light_literal(l: &DirectionalLightDef) -> String {
    format!(
        "DirectionalLightDef {{ name: {:?}.to_string(), color: {}, illuminance: {}, azimuth_deg: {}, elevation_deg: {}, shadow_maps_enabled: {}, contact_shadows_enabled: {}, shadow_depth_bias: {}, shadow_normal_bias: {}, affects_lightmapped_mesh_diffuse: {} }}",
        l.name,
        fmt_arr4(l.color),
        fmt_f32(l.illuminance),
        fmt_f32(l.azimuth_deg),
        fmt_f32(l.elevation_deg),
        l.shadow_maps_enabled,
        l.contact_shadows_enabled,
        fmt_f32(l.shadow_depth_bias),
        fmt_f32(l.shadow_normal_bias),
        l.affects_lightmapped_mesh_diffuse,
    )
}

fn emit_env_literal(e: &Environment) -> String {
    let cubemap = match &e.cubemap {
        Some(c) => format!("Some({c:?}.to_string())"),
        None => "None".to_string(),
    };
    let lights: Vec<String> = e.lights.iter().map(emit_light_literal).collect();
    let tm = match e.tonemapping {
        TonemappingMode::None => "TonemappingMode::None",
        TonemappingMode::Reinhard => "TonemappingMode::Reinhard",
        TonemappingMode::ReinhardLuminance => "TonemappingMode::ReinhardLuminance",
        TonemappingMode::AcesFitted => "TonemappingMode::AcesFitted",
        TonemappingMode::AgX => "TonemappingMode::AgX",
        TonemappingMode::SomewhatBoringDisplayTransform => "TonemappingMode::SomewhatBoringDisplayTransform",
        TonemappingMode::TonyMcMapface => "TonemappingMode::TonyMcMapface",
        TonemappingMode::BlenderFilmic => "TonemappingMode::BlenderFilmic",
    };
    format!(
        "EnvironmentValues {{ format_version: {}, clear_color: {}, cubemap: {cubemap}, skybox_brightness: {}, skybox_rotation: {}, env_intensity: {}, sky_top_color: {}, sky_horizon_color: {}, ground_color: {}, env_affects_lightmapped: {}, ambient_color: {}, ambient_brightness: {}, ambient_affects_lightmapped: {}, lights: vec![{}], ev100: {}, tonemapping: {tm}, deband_dither: {}, color_grading: {}, fog: {}, skybox_blend: None }}",
        e.format_version,
        fmt_arr4(e.clear_color),
        fmt_f32(e.skybox_brightness),
        fmt_f32(e.skybox_rotation),
        fmt_f32(e.env_intensity),
        fmt_arr4(e.sky_top_color),
        fmt_arr4(e.sky_horizon_color),
        fmt_arr4(e.ground_color),
        e.env_affects_lightmapped,
        fmt_arr4(e.ambient_color),
        fmt_f32(e.ambient_brightness),
        e.ambient_affects_lightmapped,
        lights.join(", "),
        fmt_f32(e.ev100),
        e.deband_dither,
        emit_color_grading_literal(&e.color_grading),
        emit_fog_literal(&e.fog),
    )
}
